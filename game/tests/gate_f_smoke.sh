#!/usr/bin/env bash
# Riftwrought — Prototype Zero Gate F smoke checks.
#
# Gate F is the feedback, death, settings, and test-state layer: the persistent
# Prototype App with Start New Lab / Continue Lab / Settings / Quit, the
# restrained §17 HUD, the §18 synchronized Hit / kill / player-damage feedback,
# project-authored audio for every §19 cue family, damage numbers On and Off,
# reducible shake / flashes / vibration, §20.1 Fallen with its exact killing
# source, §20.2 trusted Restart, Pause with a genuinely stopped world, the §21
# settings with safe display Keep/Revert, and two separate versioned files.
#
# This script runs every automated check Gate F is allowed to have
# (specification §25 forbids installing a test framework), and it runs the whole
# Gate E suite first — which runs Gate D, which runs Gate C, which runs Gate B,
# which runs Gate A — so a progression, encounter, combat-kernel, locomotion,
# asset, or rig regression is caught before any Gate F result is trusted.
#
# It also REBUILDS the authored audio and proves the rebuild is byte-identical,
# which is what makes "no sound was downloaded; every cue is generated by a
# script in this repository" a checkable statement rather than a claim.
#
# IT NEVER TOUCHES THE PROJECT OWNER'S OWN SAVED STATE (D-191, D-192). The Gate F
# verification writes, corrupts, and DELETES real settings and lab-state files.
# Until D-191 it wrote them to `user://prototype_settings.cfg` and
# `user://prototype_zero.cfg`, so a successful run replaced the owner's comfort
# settings and erased their laboratory progress. This script now creates a unique
# `mktemp -d` directory, hands it to every Gate F run with `--state-dir`, gives
# Godot an explicit `--log-file` inside it, removes it on exit, and FINGERPRINTS
# the production files before and after the whole run to prove they did not move.
# If the temporary directory is missing or invalid the app refuses to start and
# the verification refuses to run: there is no fall back to the real files.
#
# D-191 decided "is this isolated storage?" by comparing the store's path TEXT
# against the literal `user://…` constant, which an absolute, `..`, or symlinked
# spelling of the same directory defeats — and so, on a volume that folds case,
# does the same directory spelled in another case. Step 2b now proves the refusal
# structurally, on a startup path that writes nothing at all, against the exact
# production directory and eleven aliases of it — and step 3, the destructive
# one, does not run unless every one of those refusals held.
#
# Automated checks cannot certify feel, and Gate F's whole subject is feel. See:
#   game/tests/manual/PROTOTYPE_ZERO_TEST_MATRIX.md
#   docs/testing/PROTOTYPE_ZERO_GATE_F_REPORT.md
#   docs/testing/PROTOTYPE_ZERO_TEST_REPORT.md   (the Gate G exit review)
#
# Gate F was NOT closed by this script passing. It closed under D-193, when the
# project owner played the current experience and accepted it as sufficient for
# Prototype Zero's purpose. The fourteen rows they did not judge are recorded as
# DEFERRED BY OWNER rather than as passes, and must return during first-MVP
# vertical-slice validation. This script stays the regression gate for game/.
#
# Usage, from the repository root:
#   game/tests/gate_f_smoke.sh [--shots <dir>]
#
# --shots additionally boots the app with a real renderer and writes the Gate F
# evidence screenshots.
#
# To ask the storage guard about one path by hand, without starting the game or
# touching a single file:
#   godot --headless --path game -- --check-state-dir --state-dir <directory>

set -uo pipefail

GODOT="${GODOT:-/Applications/Godot.app/Contents/MacOS/Godot}"
EXPECTED_VERSION="4.7.2.stable"
PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_SCENE="res://scenes/app/prototype_app.tscn"
CUE_DIR="$PROJECT_DIR/assets/prototype/audio/cues"

# --- Isolated verification storage (D-191) -----------------------------------
# A unique directory per run, removed on every exit path including a failure or
# an interrupt. Nothing the verification writes can outlive it, and nothing it
# writes lands anywhere near the project owner's own files.
state_dir="$(mktemp -d "${TMPDIR:-/tmp}/riftwrought_gate_f_state.XXXXXXXX")"
trap 'rm -rf "$state_dir"' EXIT INT TERM
# CANONICAL, and it matters (D-192). $TMPDIR is a symlinked path on macOS and
# mktemp can hand back a doubled separator, so the directory this script talks
# about and the directory the engine resolves the request to would otherwise be
# two spellings of one place. `pwd -P` resolves it the way the engine does, so
# every path this script greps for is the path the engine prints.
state_dir="$(cd "$state_dir" && pwd -P)"
# Godot writes its own log into the USER data directory by default, which is the
# same directory the two state files live in. An explicit log file keeps even
# that inside the temporary directory.
godot_log="$state_dir/godot.log"

# Where the project owner's real files live, derived from the project name Godot
# itself uses for the user data directory. Step 3 asserts this guess against the
# path the engine prints, so an absence proved here cannot be an absence proved
# about the wrong directory.
project_name="$(sed -n 's/^config\/name="\(.*\)"[[:space:]]*$/\1/p' "$PROJECT_DIR/project.godot" | head -1)"
production_dir="$HOME/Library/Application Support/Godot/app_userdata/$project_name"
production_settings="$production_dir/prototype_settings.cfg"
production_lab="$production_dir/prototype_zero.cfg"

state_fingerprint() {
	# "absent" is a legitimate answer: the claim is that the run changes nothing,
	# not that a file has to exist.
	if [[ -f "$1" ]]; then
		printf '%s bytes, sha256 %s' \
			"$(wc -c < "$1" | tr -d ' ')" "$(shasum -a 256 "$1" | awk '{print $1}')"
	else
		printf 'absent'
	fi
}

production_settings_before="$(state_fingerprint "$production_settings")"
production_lab_before="$(state_fingerprint "$production_lab")"

shots_dir=""
if [[ "${1:-}" == "--shots" ]]; then
	shots_dir="${2:?--shots requires a directory}"
	mkdir -p "$shots_dir"
	shots_dir="$(cd "$shots_dir" && pwd)"
fi

failures=0

# NOTE on the pattern below. Godot's output is written to a log FIRST and the log
# is then grepped, rather than piping Godot through `tee ... | grep -q`. With
# `set -o pipefail`, `grep -q` exits the moment it matches and `tee` can then die
# on EPIPE, failing the whole pipeline even though the verification passed. That
# race is timing-dependent, which is the worst kind of flaky: it reported a
# regression that had not happened.

step() {
	printf '\n=== %s\n' "$1"
}

check() {
	local label="$1"
	shift
	if "$@" > /tmp/riftwrought_gate_f_step.log 2>&1; then
		printf '  PASS  %s\n' "$label"
	else
		printf '  FAIL  %s\n' "$label"
		sed 's/^/        /' /tmp/riftwrought_gate_f_step.log | tail -20
		failures=$((failures + 1))
	fi
}

cue_fingerprint() {
	# One hash over every generated cue, so a rebuild can be compared to the
	# tree it replaced.
	shasum -a 256 "$CUE_DIR"/*.res 2>/dev/null | awk '{print $1}' | sort | shasum -a 256 | awk '{print $1}'
}

step "0. Isolated verification storage (D-191)"
printf '  state directory: %s\n' "$state_dir"
printf '  Godot log file:  %s\n' "$godot_log"
printf '  production settings before: %s\n' "$production_settings_before"
printf '  production lab state before: %s\n' "$production_lab_before"
if [[ -d "$state_dir" && -w "$state_dir" ]]; then
	printf '  PASS  a unique, writable temporary directory was created for this run\n'
else
	printf '  FAIL  the temporary state directory is missing or not writable\n'
	failures=$((failures + 1))
fi

step "0b. Engine baseline"
version="$("$GODOT" --version 2>/dev/null | tail -1)"
printf '  installed: %s\n' "$version"
if [[ "$version" != "$EXPECTED_VERSION"* ]]; then
	printf '  FAIL  expected %s (locked by D-167); report the mismatch before upgrading the project.\n' "$EXPECTED_VERSION"
	failures=$((failures + 1))
else
	printf '  PASS  matches the locked %s baseline\n' "$EXPECTED_VERSION"
fi

step "1. Gate E regression (which reruns Gate D, Gate C, Gate B, and Gate A)"
if "$PROJECT_DIR/tests/gate_e_smoke.sh" > /tmp/riftwrought_gate_e_from_f.log 2>&1; then
	printf '  PASS  gate_e_smoke.sh still passes after the Gate F work\n'
	grep -E "VERIFICATION: PASS" /tmp/riftwrought_gate_b_verify.log \
		/tmp/riftwrought_gate_c_verify.log /tmp/riftwrought_gate_d_verify.log \
		/tmp/riftwrought_gate_e_verify.log 2>/dev/null | sed 's#^.*/##' | sed 's/^/        /'
else
	printf '  FAIL  gate_e_smoke.sh regressed\n'
	sed 's/^/        /' /tmp/riftwrought_gate_e_from_f.log | tail -40
	failures=$((failures + 1))
fi

step "2. The authored audio rebuilds byte-identically"
before="$(cue_fingerprint)"
printf '  cue tree before: %s\n' "${before:0:16}"
if "$GODOT" --headless --log-file "$godot_log" --path "$PROJECT_DIR" \
	--script res://scripts/tools/build_prototype_audio.gd \
	> /tmp/riftwrought_gate_f_audio.log 2>&1 \
	&& grep -q "PROTOTYPE AUDIO BUILD: PASS" /tmp/riftwrought_gate_f_audio.log; then
	after="$(cue_fingerprint)"
	printf '  cue tree after:  %s\n' "${after:0:16}"
	grep -E "variants, [0-9]+ families" /tmp/riftwrought_gate_f_audio.log | sed 's/^/      /'
	if [[ "$before" == "$after" ]]; then
		printf '  PASS  every cue regenerated identically from scripts/tools/build_prototype_audio.gd\n'
	else
		printf '  FAIL  the rebuild changed the cue tree; the generator is not deterministic\n'
		failures=$((failures + 1))
	fi
else
	printf '  FAIL  the audio generator did not complete\n'
	sed 's/^/        /' /tmp/riftwrought_gate_f_audio.log | tail -20
	failures=$((failures + 1))
fi

# No sound FILE of any kind may exist under the prototype audio tree: every cue
# is a generated Godot resource, so nothing ever entered the import pipeline.
samples="$(find "$PROJECT_DIR/assets/prototype/audio" \
	\( -name '*.wav' -o -name '*.ogg' -o -name '*.mp3' -o -name '*.flac' -o -name '*.aif*' \) 2>/dev/null | wc -l | tr -d ' ')"
printf '  imported sound files under assets/prototype/audio: %s\n' "$samples"
if [[ "$samples" == "0" ]]; then
	printf '  PASS  no downloaded or imported sound exists anywhere in the project\n'
else
	printf '  FAIL  %s imported sound files exist; D-189 authorises authored cues only\n' "$samples"
	failures=$((failures + 1))
fi

step "2b. Every spelling of the production directory is refused, on a NON-WRITING startup path (D-192)"
# Including its CASE. On this Mac the filesystem folds case, so
# `…/app_userdata/riftwrought — prototype zero` is the same directory as
# `…/app_userdata/Riftwrought — Prototype Zero` — and the first version of this
# guard, which compared canonical real paths with `==`, accepted it.
# D-191 kept the verification off the project owner's files by injecting a
# `--state-dir`, and decided whether that had worked by comparing the store's
# path STRING against the literal `user://…` constant. That is an alias test,
# not an identity test: hand `--state-dir` the real Godot user data directory and
# the resulting absolute paths are different strings naming the same two files,
# so the guard would have called production storage isolated and this suite would
# have run its corruption, deletion, and Reset checks against the real save.
#
# The guard is now structural — every path is resolved to one canonical real path
# before it is compared — and the refusal is checked here, on `--check-state-dir`:
# a startup path that resolves the request, prints the decision, and quits
# BEFORE either store is constructed, so proving the refusal never opens, writes,
# or removes a single file anywhere. The production files are fingerprinted
# around every one of these checks.
#
# THE DESTRUCTIVE VERIFICATION IN STEP 3 DOES NOT RUN IF ANY OF THEM FAILS.
guard_failures=0
guard_log=/tmp/riftwrought_gate_f_guard.log

guard_fingerprints() {
	printf '%s | %s' "$(state_fingerprint "$production_settings")" "$(state_fingerprint "$production_lab")"
}

# Runs the non-writing probe against a path that MUST be refused, and proves the
# project owner's own two files did not move while it was refused.
guard_refuses() {
	local label="$1"
	local requested="$2"
	local before after
	before="$(guard_fingerprints)"
	if "$GODOT" --headless --log-file "$godot_log" --path "$PROJECT_DIR" \
		-- --check-state-dir --state-dir "$requested" > "$guard_log" 2>&1; then
		printf '  FAIL  %s — the app started instead of refusing\n' "$label"
		guard_failures=$((guard_failures + 1))
	elif grep -q "own user data directory" "$guard_log"; then
		printf '  PASS  %s\n' "$label"
	else
		printf '  FAIL  %s — it refused, but not because the path is the production directory\n' "$label"
		sed 's/^/        /' "$guard_log" | tail -8
		guard_failures=$((guard_failures + 1))
	fi
	after="$(guard_fingerprints)"
	if [[ "$before" == "$after" ]]; then
		printf '        production files unchanged across this check\n'
	else
		printf '  FAIL  %s changed a production file: %s -> %s\n' "$label" "$before" "$after"
		guard_failures=$((guard_failures + 1))
	fi
}

# A symlink alias, made inside the run's own temporary directory so it is removed
# with it. Nothing is moved, copied, or backed up: the link is a second NAME for
# the production directory and is only ever handed to the guard.
alias_link="$state_dir/production_directory_alias"
ln -s "$production_dir" "$alias_link" 2>/dev/null || true

# CASE SPELLINGS. `tr` with explicit ASCII ranges is byte-wise, so the em dash in
# "Riftwrought — Prototype Zero" passes through untouched while the letters
# change. This Mac's filesystem folds case, so all four of these name the one
# directory the project owner's settings live in — and the first D-192 guard,
# which compared canonical paths with `==`, ACCEPTED the lowercase one.
lower_dir="$(printf '%s' "$production_dir" | tr 'A-Z' 'a-z')"
lower_leaf="$(printf '%s' "$project_name" | tr 'A-Z' 'a-z')"
mixed_dir="$(dirname "$production_dir")/$(printf '%s' "$project_name" | tr 'a-z' 'A-Z')"

printf '  production directory: %s\n' "$production_dir"
printf '  lowercase spelling:   %s\n' "$lower_dir"
printf '  mixed-case spelling:  %s\n' "$mixed_dir"
printf '  fingerprints before this step: %s\n' "$(guard_fingerprints)"

guard_refuses "the Godot user:// root itself"            "user://"
guard_refuses "the production directory, spelled out"    "$production_dir"
guard_refuses "a trailing separator on it"               "$production_dir/"
guard_refuses "a '.' component in it"                    "$production_dir/./"
guard_refuses "a '..' round trip through its parent"     "$production_dir/../$project_name"
guard_refuses "a doubled separator in it"                "$production_dir//"
guard_refuses "it spelled entirely in lower case"        "$lower_dir"
guard_refuses "it spelled entirely in upper case"        "$mixed_dir"
guard_refuses "lower case plus a '..' round trip"        "$lower_dir/../$lower_leaf"
guard_refuses "upper case plus a '.' component"          "$mixed_dir/./"
guard_refuses "a lower-case directory INSIDE it"         "$lower_dir/logs"
if [[ -L "$alias_link" ]]; then
	guard_refuses "a symlink pointing at it"             "$alias_link"
else
	printf '  FAIL  the symlink alias could not be created, so that spelling is untested\n'
	guard_failures=$((guard_failures + 1))
fi
rm -f "$alias_link"

# The case spellings are only a test of anything if this filesystem really does
# fold case. Proved here rather than assumed: the lowercase directory has to be
# reachable from the shell too.
if [[ -d "$lower_dir" ]]; then
	printf '  PASS  this filesystem resolves the lower-case spelling to the same directory\n'
else
	printf '  FAIL  the lower-case spelling does not exist here, so those refusals prove nothing\n'
	guard_failures=$((guard_failures + 1))
fi

# The positive control. A guard that refuses everything protects nothing, so the
# run's own isolated directory must be ACCEPTED and both files must resolve
# inside it.
before_accept="$(guard_fingerprints)"
if "$GODOT" --headless --log-file "$godot_log" --path "$PROJECT_DIR" \
	-- --check-state-dir --state-dir "$state_dir" > "$guard_log" 2>&1 \
	&& grep -q "^  resolved:  $state_dir\$" "$guard_log" \
	&& grep -q "^  settings:  $state_dir/prototype_settings.cfg\$" "$guard_log" \
	&& grep -q "^  lab state: $state_dir/prototype_zero.cfg\$" "$guard_log"; then
	printf '  PASS  this run'"'"'s own temporary directory is accepted, and both files resolve inside it\n'
else
	printf '  FAIL  the isolated run directory was not accepted, or its files did not resolve inside it\n'
	sed 's/^/        /' "$guard_log" | tail -12
	guard_failures=$((guard_failures + 1))
fi

# The engine's canonical answer and the shell's must agree, or the refusals above
# would be protecting a directory that is not the one the game actually uses.
production_dir_real="$(cd "$production_dir" 2>/dev/null && pwd -P)"
reported_real="$(grep -m1 '^  production directory: ' "$guard_log" | sed 's/^  production directory: //')"
printf '  engine resolves the production directory to: %s\n' "${reported_real:-<not reported>}"
printf '  this script resolves it to:                  %s\n' "${production_dir_real:-<missing>}"
if [[ -n "$production_dir_real" && "$reported_real" == "$production_dir_real" ]]; then
	printf '  PASS  the engine and the shell resolve the production directory identically\n'
else
	printf '  FAIL  the engine and the shell disagree about where the production directory is\n'
	guard_failures=$((guard_failures + 1))
fi

# And an ORDINARY launch is untouched by all of this: no --state-dir, and both
# stores are still the two user:// constants.
if "$GODOT" --headless --log-file "$godot_log" --path "$PROJECT_DIR" \
	-- --check-state-dir > "$guard_log" 2>&1 \
	&& grep -q "this is an ordinary launch" "$guard_log" \
	&& grep -q "^  settings:  user://prototype_settings.cfg\$" "$guard_log" \
	&& grep -q "^  lab state: user://prototype_zero.cfg\$" "$guard_log"; then
	printf '  PASS  an ordinary launch still uses user://prototype_settings.cfg and user://prototype_zero.cfg\n'
else
	printf '  FAIL  an ordinary launch no longer reports the two production files\n'
	sed 's/^/        /' "$guard_log" | tail -12
	guard_failures=$((guard_failures + 1))
fi

after_step="$(guard_fingerprints)"
printf '  fingerprints after this step:  %s\n' "$after_step"
if [[ "$(printf '%s' "$before_accept")" == "$after_step" ]]; then
	printf '  PASS  the project owner'"'"'s own files did not move during any refusal check\n'
else
	printf '  FAIL  a production file changed during the refusal checks\n'
	guard_failures=$((guard_failures + 1))
fi

if [[ $guard_failures -ne 0 ]]; then
	printf '\n'
	printf 'The storage guard did not hold, so the DESTRUCTIVE Gate F verification was not run.\n'
	printf 'It writes, corrupts, and deletes real settings and lab-state files, and it may only\n'
	printf 'do that once the guard that keeps it off the production files has been proved.\n'
	printf 'GATE F SMOKE CHECKS: %d FAILURE(S) in the storage guard\n' "$guard_failures"
	exit 1
fi

step "3. Gate F feedback, death, settings, and test-state verification (headless)"
if "$GODOT" --headless --log-file "$godot_log" --path "$PROJECT_DIR" \
	-- --verify-f --state-dir "$state_dir" > /tmp/riftwrought_gate_f_verify.log 2>&1; grep -q "GATE F VERIFICATION: PASS" /tmp/riftwrought_gate_f_verify.log; then
	grep -E "^  (defaults:|aim assistance 0|longest cue|ordinary |improved |40 paused frames|killing source|the file holds exactly|[A-Z]+ kill |after |applied |kept:|timed out|rejected:|Life [0-9]|numbers O)" \
		/tmp/riftwrought_gate_f_verify.log | head -30
	printf '  PASS  settings, pause-safe clocks, neutral doors, the killing source, Fallen,\n'
	printf '        Restart, milestone saves, Continue at every milestone, invalid-file recovery,\n'
	printf '        display Keep/Revert and startup recovery, damage numbers Off, cue routing,\n'
	printf '        Master volume, aim assistance, storage isolation, and scope\n'
else
	printf '  FAIL  Gate F verification\n'
	grep -E "FAIL|VERIFICATION" /tmp/riftwrought_gate_f_verify.log | sed 's/^/        /' | tail -25
	failures=$((failures + 1))
fi

# The engine's own idea of where the production files live, so the fingerprints
# above cannot be an absence proved about the wrong directory.
reported="$(grep -m1 '^  production:' /tmp/riftwrought_gate_f_verify.log | sed 's/^  production:[[:space:]]*//')"
printf '  engine reports production files at: %s\n' "${reported:-<not reported>}"
if [[ "$reported" == "$production_settings | $production_lab" ]]; then
	printf '  PASS  the production paths this script watches are the ones the engine uses\n'
else
	printf '  FAIL  this script watches %s | %s, which is not what the engine reported\n' \
		"$production_settings" "$production_lab"
	failures=$((failures + 1))
fi

# And the harness really did write somewhere else.
if grep -q "^  state directory: $state_dir\$" /tmp/riftwrought_gate_f_verify.log; then
	printf '  PASS  the verification wrote its settings and lab files into %s\n' "$state_dir"
else
	printf '  FAIL  the verification did not report the temporary state directory\n'
	failures=$((failures + 1))
fi

step "4. Headless startup of the project main scene"
check "boots the Prototype App to its title screen and exits cleanly" \
	"$GODOT" --headless --log-file "$godot_log" --path "$PROJECT_DIR" "$APP_SCENE" \
	--quit-after 180 -- --state-dir "$state_dir"

step "4b. A verification run without isolated storage refuses to start"
# The point of the correction is that there is NO fall back to the production
# files, so the refusal is itself a checked behaviour.
if "$GODOT" --headless --log-file "$godot_log" --path "$PROJECT_DIR" \
	-- --verify-f --state-dir "$state_dir/definitely-not-a-directory" \
	> /tmp/riftwrought_gate_f_refusal.log 2>&1; then
	printf '  FAIL  a run with an invalid state directory started anyway\n'
	failures=$((failures + 1))
elif grep -q "refusing to start" /tmp/riftwrought_gate_f_refusal.log; then
	printf '  PASS  an invalid --state-dir refuses to start rather than using the real files\n'
else
	printf '  FAIL  the refusal did not name itself\n'
	sed 's/^/        /' /tmp/riftwrought_gate_f_refusal.log | tail -10
	failures=$((failures + 1))
fi

if [[ -n "$shots_dir" ]]; then
	step "5. Rendered evidence screenshots"
	if "$GODOT" --log-file "$godot_log" --path "$PROJECT_DIR" --resolution 1280x720 \
		-- --verify-f --state-dir "$state_dir" --shots "$shots_dir" \
		> /tmp/riftwrought_gate_f_shots.log 2>&1; then
		printf '  PASS  wrote screenshots to %s\n' "$shots_dir"
		grep -E "GATE F VERIFICATION" /tmp/riftwrought_gate_f_shots.log
	else
		printf '  FAIL  rendered run\n'
		sed 's/^/        /' /tmp/riftwrought_gate_f_shots.log | tail -30
		failures=$((failures + 1))
	fi
fi

step "6. The project owner's own files are byte-for-byte untouched (D-191)"
production_settings_after="$(state_fingerprint "$production_settings")"
production_lab_after="$(state_fingerprint "$production_lab")"
printf '  %s\n    before %s\n    after  %s\n' \
	"$production_settings" "$production_settings_before" "$production_settings_after"
printf '  %s\n    before %s\n    after  %s\n' \
	"$production_lab" "$production_lab_before" "$production_lab_after"
if [[ "$production_settings_before" == "$production_settings_after" \
	&& "$production_lab_before" == "$production_lab_after" ]]; then
	printf '  PASS  the real settings and lab files are unchanged, or still absent\n'
else
	printf '  FAIL  a production state file changed during the run\n'
	failures=$((failures + 1))
fi

printf '\n'
if [[ $failures -eq 0 ]]; then
	printf 'GATE F SMOKE CHECKS: PASS\n'
	printf 'Automated checks cannot certify feel, and feel is what Gate F is FOR. Gate F\n'
	printf 'closed by project-owner acceptance under D-193, and Gate G — the exit review —\n'
	printf 'is docs/testing/PROTOTYPE_ZERO_TEST_REPORT.md (D-194). Fourteen manual rows the\n'
	printf 'owner did not judge are recorded as DEFERRED BY OWNER, not as passes, and must\n'
	printf 'return during first-MVP vertical-slice validation. This script remains the\n'
	printf 'regression gate: run it before and after any change under game/.\n'
	exit 0
fi
printf 'GATE F SMOKE CHECKS: %d FAILURE(S)\n' "$failures"
exit 1
